def list_setores():
    return [
        {"setor": s, "capelas": caps, "total_capelas": len(caps)}
        for s, caps in SETORES_CAPELAS.items()
    ]


def list_capelas():
    items = []
    for setor, capelas in SETORES_CAPELAS.items():
        for cap in capelas:
            items.append({"capela": cap, "setor": setor})
    items.sort(key=lambda x: x["capela"])
    return items
